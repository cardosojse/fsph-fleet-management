-- V1-V25 belong to the published route-based deployment and remain immutable.
-- Expand the catalog without removing existing transport/route permissions.
ALTER TABLE role_permissions DROP CONSTRAINT chk_role_permissions_permission;
ALTER TABLE role_permissions ADD CONSTRAINT chk_role_permissions_permission CHECK (permission IN (
    'USERS_READ', 'USERS_WRITE', 'SECTORS_READ', 'SECTORS_WRITE',
    'PERMISSIONS_READ', 'PERMISSIONS_WRITE', 'VEHICLES_READ', 'VEHICLES_WRITE',
    'DRIVERS_READ', 'DRIVERS_WRITE', 'TRANSPORTS_READ', 'TRANSPORTS_REQUEST',
    'TRANSPORTS_MANAGE', 'ROUTES_READ', 'ROUTES_MANAGE', 'ROUTES_EXECUTE',
    'VEHICLES_ASSIGNED_READ', 'TRIPS_WRITE', 'TRIPS_READ',
    'MAINTENANCES_READ', 'MAINTENANCES_WRITE',
    'FUEL_STATIONS_READ', 'FUEL_STATIONS_WRITE', 'FUELINGS_READ', 'FUELINGS_WRITE',
    'TRIP_REQUESTS_READ', 'TRIP_REQUESTS_WRITE', 'TRIP_REQUESTS_MANAGE', 'NOTIFICATIONS_READ',
    'SVO_TEAMS_READ', 'SVO_TEAMS_WRITE', 'SVO_SHIFTS_READ', 'SVO_SHIFTS_WRITE',
    'AUDIT_LOGS_READ', 'FUEL_CARDS_READ', 'FUEL_CARDS_WRITE',
    'SVO_REQUESTS_READ', 'SVO_REQUESTS_WRITE', 'SVO_REQUESTS_MANAGE'
));

-- Extend only untouched default role matrices. An administrator's custom access
-- decisions remain intact; new permissions can be granted through the existing UI.
WITH defaults(role, permissions) AS (VALUES
    ('EMPLOYEE', ARRAY['SECTORS_READ', 'TRIP_REQUESTS_WRITE', 'NOTIFICATIONS_READ',
        'TRANSPORTS_READ', 'TRANSPORTS_REQUEST']),
    ('GESTOR_FROTA', ARRAY['SECTORS_READ', 'VEHICLES_READ', 'VEHICLES_WRITE',
        'DRIVERS_READ', 'DRIVERS_WRITE', 'MAINTENANCES_READ', 'MAINTENANCES_WRITE',
        'FUEL_STATIONS_READ', 'FUEL_STATIONS_WRITE', 'FUELINGS_READ', 'FUELINGS_WRITE',
        'TRIP_REQUESTS_READ', 'TRIP_REQUESTS_WRITE', 'TRIP_REQUESTS_MANAGE',
        'NOTIFICATIONS_READ', 'TRIPS_READ', 'TRANSPORTS_READ', 'TRANSPORTS_REQUEST',
        'TRANSPORTS_MANAGE', 'ROUTES_READ', 'ROUTES_MANAGE']),
    ('GESTOR_SVO', ARRAY['SECTORS_READ']),
    ('ATENDENTE_SVO', ARRAY['SECTORS_READ']),
    ('EQUIPE_COLETA_SVO', ARRAY['SECTORS_READ'])
), default_roles AS (
    SELECT rp.role FROM role_permissions rp JOIN defaults d ON d.role = rp.role
    GROUP BY rp.role, d.permissions
    HAVING count(*) = cardinality(d.permissions)
        AND bool_and(rp.permission = ANY(d.permissions))
)
INSERT INTO role_permissions (role, permission)
SELECT grants.role, grants.permission FROM (VALUES
    ('ADMIN', 'SVO_TEAMS_READ'), ('ADMIN', 'SVO_TEAMS_WRITE'),
    ('ADMIN', 'SVO_SHIFTS_READ'), ('ADMIN', 'SVO_SHIFTS_WRITE'),
    ('ADMIN', 'AUDIT_LOGS_READ'), ('ADMIN', 'FUEL_CARDS_READ'), ('ADMIN', 'FUEL_CARDS_WRITE'),
    ('ADMIN', 'SVO_REQUESTS_READ'), ('ADMIN', 'SVO_REQUESTS_WRITE'), ('ADMIN', 'SVO_REQUESTS_MANAGE'),
    ('GESTOR_FROTA', 'SVO_TEAMS_READ'), ('GESTOR_FROTA', 'SVO_TEAMS_WRITE'),
    ('GESTOR_FROTA', 'SVO_SHIFTS_READ'), ('GESTOR_FROTA', 'SVO_SHIFTS_WRITE'),
    ('GESTOR_FROTA', 'FUEL_CARDS_READ'), ('GESTOR_FROTA', 'FUEL_CARDS_WRITE'),
    ('GESTOR_SVO', 'SVO_TEAMS_READ'), ('GESTOR_SVO', 'SVO_TEAMS_WRITE'),
    ('GESTOR_SVO', 'SVO_SHIFTS_READ'), ('GESTOR_SVO', 'SVO_SHIFTS_WRITE'),
    ('GESTOR_SVO', 'SVO_REQUESTS_READ'), ('GESTOR_SVO', 'SVO_REQUESTS_WRITE'), ('GESTOR_SVO', 'SVO_REQUESTS_MANAGE'),
    ('ATENDENTE_SVO', 'SVO_TEAMS_READ'), ('ATENDENTE_SVO', 'SVO_SHIFTS_READ'),
    ('ATENDENTE_SVO', 'SVO_REQUESTS_READ'), ('ATENDENTE_SVO', 'SVO_REQUESTS_WRITE'), ('ATENDENTE_SVO', 'SVO_REQUESTS_MANAGE'),
    ('EQUIPE_COLETA_SVO', 'SVO_TEAMS_READ'), ('EQUIPE_COLETA_SVO', 'SVO_SHIFTS_READ'),
    ('EMPLOYEE', 'SVO_REQUESTS_WRITE')
) AS grants(role, permission)
WHERE grants.role = 'ADMIN' OR grants.role IN (SELECT role FROM default_roles)
ON CONFLICT (role, permission) DO NOTHING;
